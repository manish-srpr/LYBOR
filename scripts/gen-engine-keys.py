D = "src/lib/i18n/messages"
for loc in LOCALES:
    path = os.path.join(D, f"{loc}.ts")
    src = io.open(path, encoding="utf-8").read()
    if '"risk.MISSING_CHECK_OUT.detail"' in src:
        print(f"  skip {loc}")
        continue

    lines = ["", "  // --- Domain engine output (risk rules) ---"]
    for key, per_locale in K.items():
        lines.append(f"  {q(key)}: {q(per_locale[loc])},")
    block = "\n".join(lines) + "\n"

    for marker, close in (("\n} as const;", "} as const;"), ("\n};", "};")):
        if marker in src:
            src = src.replace(marker, block + close, 1)
            break
    else:
        raise SystemExit(f"no closing marker in {loc}")

    io.open(path, "w", encoding="utf-8", newline="\n").write(src)
    print(f"  ok   {loc}  (+{len(K)} keys)")

