for loc in LOCALES:
    path = os.path.join(D, f"{loc}.ts")
    src = io.open(path, encoding="utf-8").read()
    if '"notif.SYSTEM.title"' in src:
        print(f"  skip {loc} (already present)")
        continue

    lines = ["", "  // --- Notification copy (rendered from type + params at read time) ---"]
    for ntype, per_locale in N.items():
        title, body = per_locale[loc]
        lines.append(f'  "notif.{ntype}.title": {_q(title)},')
        lines.append(f'  "notif.{ntype}.body": {_q(body)},')

    block = "\n".join(lines) + "\n"
    # en.ts closes its literal with "} as const;", every other catalog with "};".
    for marker, close in (("\n} as const;", "} as const;"), ("\n};", "};")):
        if marker in src:
            src = src.replace(marker, block + close, 1)
            break
    else:
        raise SystemExit(f"no closing marker found in {loc}")
    io.open(path, "w", encoding="utf-8", newline="\n").write(src)
    print(f"  ok   {loc}  (+{len(N) * 2} keys)")

